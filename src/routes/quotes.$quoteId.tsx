import { useSuspenseQuery } from "@tanstack/react-query";
import { createFileRoute, Link } from "@tanstack/react-router";
import { ArrowLeft, Download } from "lucide-react";
import { StatusBadge } from "#/components/status-badge";
import { Button } from "#/components/ui/button";
import { formatMYR } from "#/lib/money";
import { orpc } from "#/orpc/client";

export const Route = createFileRoute("/quotes/$quoteId")({
	loader: ({ context, params }) =>
		context.queryClient.ensureQueryData(
			orpc.quotes.get.queryOptions({ input: { quoteId: params.quoteId } }),
		),
	component: QuotePage,
});

function QuotePage() {
	const { quoteId } = Route.useParams();
	const { data: q } = useSuspenseQuery(
		orpc.quotes.get.queryOptions({ input: { quoteId } }),
	);
	const business = q.business;

	return (
		<div className="min-h-dvh bg-muted/40 px-4 py-8">
			<div className="mx-auto mb-4 flex max-w-3xl items-center justify-between">
				<Link
					to="/"
					search={{ b: q.businessId, c: q.conversation?.id, r: q.requestId }}
					className="flex items-center gap-1 text-sm text-muted-foreground hover:text-foreground"
				>
					<ArrowLeft className="size-4" /> Back to workspace
				</Link>
				<Button asChild size="sm">
					<a href={`/api/quotes/${q.id}/pdf`} target="_blank" rel="noreferrer">
						<Download className="size-4" /> Download PDF
					</a>
				</Button>
			</div>

			<article className="mx-auto max-w-3xl rounded-xl border bg-card p-8 shadow-sm">
				<header className="flex flex-wrap justify-between gap-4">
					<div>
						<h1 className="text-xl font-bold">{business?.name}</h1>
						<p className="text-sm text-muted-foreground">{business?.address}</p>
						<p className="text-sm text-muted-foreground">{business?.phone}</p>
					</div>
					<div className="text-right">
						<p className="text-xl font-bold tracking-wide">QUOTATION</p>
						<p className="font-medium">{q.number}</p>
						<div className="mt-1">
							<StatusBadge
								status={q.status === "draft" ? "draft_ready" : q.status}
							/>
						</div>
					</div>
				</header>

				<div className="mt-8 flex flex-wrap justify-between gap-4 text-sm">
					<div>
						<p className="text-muted-foreground">Prepared for</p>
						<p className="font-semibold">{q.conversation?.customerName}</p>
					</div>
					<div className="text-right text-muted-foreground">
						<p>Date: {q.createdAt.toLocaleDateString("en-MY")}</p>
						<p>Valid until: {q.validUntil.toLocaleDateString("en-MY")}</p>
						{q.decidedBy && q.decidedAt && (
							<p>
								{q.status === "approved" ? "Approved" : "Rejected"} by{" "}
								{q.decidedBy.name}, {q.decidedAt.toLocaleDateString("en-MY")}
							</p>
						)}
					</div>
				</div>

				<div className="mt-8 overflow-x-auto">
					<table className="w-full text-sm">
						<thead>
							<tr className="border-b text-left text-muted-foreground">
								<th className="py-2 font-medium">Description</th>
								<th className="py-2 text-right font-medium">Qty</th>
								<th className="py-2 text-right font-medium">Unit price</th>
								<th className="py-2 text-right font-medium">Amount</th>
							</tr>
						</thead>
						<tbody>
							{q.lineItems.map((l, i) => (
								<tr
									key={`${i}-${l.description}`}
									className="border-b align-top"
								>
									<td className="py-2">
										{l.description}
										{l.notes && (
											<p className="text-xs text-muted-foreground">{l.notes}</p>
										)}
									</td>
									<td className="py-2 text-right whitespace-nowrap">
										{l.quantity} {l.unit}
									</td>
									<td className="py-2 text-right tabular-nums">
										{formatMYR(l.unitPriceSen)}
									</td>
									<td className="py-2 text-right tabular-nums">
										{formatMYR(l.amountSen)}
									</td>
								</tr>
							))}
						</tbody>
					</table>
				</div>

				<dl className="mt-4 ml-auto w-64 space-y-1 text-sm">
					<div className="flex justify-between text-muted-foreground">
						<dt>Subtotal</dt>
						<dd className="tabular-nums">{formatMYR(q.subtotalSen)}</dd>
					</div>
					{business?.sstRegistered && (
						<div className="flex justify-between text-muted-foreground">
							<dt>SST ({business.sstRateBps / 100}%)</dt>
							<dd className="tabular-nums">{formatMYR(q.sstSen)}</dd>
						</div>
					)}
					<div className="flex justify-between border-t pt-1 text-base font-semibold">
						<dt>Total</dt>
						<dd className="tabular-nums">{formatMYR(q.totalSen)}</dd>
					</div>
				</dl>

				{q.notes && (
					<section className="mt-8 text-sm">
						<h2 className="font-semibold">Notes</h2>
						<p className="whitespace-pre-wrap text-muted-foreground">
							{q.notes}
						</p>
					</section>
				)}

				<p className="mt-10 text-xs text-muted-foreground">
					Demo document generated by Quora Chat with synthetic data. Not a real
					business or tax invoice.
				</p>
			</article>
		</div>
	);
}
