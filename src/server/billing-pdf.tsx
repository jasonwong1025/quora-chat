/**
 * Billing documents: invoice, official receipt, statement of account and
 * completion report. Same look as the quotation PDF.
 */
import {
	Document,
	Page,
	renderToBuffer,
	Text,
	View,
} from "@react-pdf/renderer";
import { eq } from "drizzle-orm";
import { getDb, schema } from "#/db";
import { triggerLabel } from "#/lib/billing";
import { formatMYR } from "#/lib/money";
import { statementFor } from "./billing";
import { PdfBrand, s } from "./quote-pdf";

type Business = typeof schema.businesses.$inferSelect;
const day = (d: Date) =>
	d.toLocaleDateString("en-MY", { timeZone: "Asia/Kuala_Lumpur" });

function Header(props: {
	business: Business;
	title: string;
	number: string;
	status?: string;
}) {
	return (
		<View style={s.between}>
			<PdfBrand>
				<Text style={s.h1}>{props.business.name}</Text>
				<Text style={s.muted}>{props.business.address}</Text>
				<Text style={s.muted}>{props.business.phone}</Text>
			</PdfBrand>
			<View style={{ alignItems: "flex-end" }}>
				<Text style={s.h1}>{props.title}</Text>
				<Text>{props.number}</Text>
				{props.status ? <Text style={s.muted}>{props.status}</Text> : null}
			</View>
		</View>
	);
}

function Parties(props: { customer: string; right: [string, string][] }) {
	return (
		<View style={[s.between, { marginTop: 24 }]}>
			<View>
				<Text style={s.muted}>Bill to</Text>
				<Text style={s.bold}>{props.customer}</Text>
			</View>
			<View style={{ alignItems: "flex-end" }}>
				{props.right.map(([k, v]) => (
					<Text key={k} style={s.muted}>
						{k}: {v}
					</Text>
				))}
			</View>
		</View>
	);
}

function Footer() {
	return (
		<Text style={s.footer} fixed>
			Demo document generated by Quora Chat with synthetic data. Not a real
			business or tax invoice.
		</Text>
	);
}

function Row(props: { cells: string[]; bold?: boolean }) {
	return (
		<View style={[s.tr, props.bold ? s.bold : {}]}>
			<Text style={s.cDesc}>{props.cells[0]}</Text>
			{props.cells.slice(1).map((c, i) => (
				// biome-ignore lint/suspicious/noArrayIndexKey: fixed columns
				<Text key={i} style={s.cAmt}>
					{c}
				</Text>
			))}
		</View>
	);
}

function Head(props: { cells: string[] }) {
	return (
		<View style={s.th}>
			<Text style={s.cDesc}>{props.cells[0]}</Text>
			{props.cells.slice(1).map((c) => (
				<Text key={c} style={s.cAmt}>
					{c}
				</Text>
			))}
		</View>
	);
}

async function context(quoteId: string) {
	const st = await statementFor(quoteId);
	const job = await getDb().query.jobs.findFirst({
		where: eq(schema.jobs.quoteId, quoteId),
	});
	return { ...st, job };
}

export async function renderInvoicePdf(invoiceId: string) {
	const invoice = await getDb().query.invoices.findFirst({
		where: eq(schema.invoices.id, invoiceId),
	});
	if (!invoice) return null;
	const c = await context(invoice.quoteId);
	const instalment = c.plan[invoice.instalment];
	const doc = (
		<Document title={invoice.number} author={c.business.name}>
			<Page size="A4" style={s.page}>
				<Header
					business={c.business}
					title="INVOICE"
					number={invoice.number}
					status={
						invoice.status === "paid"
							? "Paid"
							: invoice.status === "void"
								? "Cancelled"
								: "Payment pending"
					}
				/>
				<Parties
					customer={c.conversation.customerName}
					right={[
						["Date", day(invoice.issuedAt)],
						["Due", day(invoice.dueAt)],
						["Quotation", c.quote.number],
						...(c.job ? ([["Job", c.job.number]] as [string, string][]) : []),
					]}
				/>
				<Head cells={["Description", "Amount"]} />
				<Row
					cells={[
						`${invoice.label} (${invoice.percent}% of ${c.quote.number}${instalment ? `, ${triggerLabel(instalment)}` : ""})`,
						formatMYR(invoice.amountSen),
					]}
				/>
				<View style={s.totals}>
					<View
						style={[s.totalRow, s.bold, { borderTopWidth: 1, paddingTop: 4 }]}
					>
						<Text>Amount due</Text>
						<Text>{formatMYR(invoice.amountSen)}</Text>
					</View>
					<Text style={[s.muted, { marginTop: 4, fontSize: 8 }]}>
						{c.business.sstRegistered ? "Includes SST as quoted." : ""}
					</Text>
				</View>
				<View style={{ marginTop: 24 }}>
					<Text style={s.bold}>What this quotation covers</Text>
					{c.quote.lineItems
						.filter((l) => !l.charge || l.charge === "one_time")
						.map((l, i) => (
							// biome-ignore lint/suspicious/noArrayIndexKey: lines have no id
							<Text key={i} style={[s.muted, { marginTop: 2 }]}>
								• {l.description} × {l.quantity} {l.unit}
							</Text>
						))}
				</View>
				<View style={{ marginTop: 18 }}>
					<Text style={s.bold}>How to pay</Text>
					<Text style={s.muted}>
						Tap "Review and pay" on this invoice in WhatsApp.
					</Text>
				</View>
				<Footer />
			</Page>
		</Document>
	);
	return { buffer: await renderToBuffer(doc), name: `${invoice.number}.pdf` };
}

export async function renderReceiptPdf(paymentId: string) {
	const payment = await getDb().query.payments.findFirst({
		where: eq(schema.payments.id, paymentId),
	});
	if (!payment) return null;
	const invoice = await getDb().query.invoices.findFirst({
		where: eq(schema.invoices.id, payment.invoiceId),
	});
	if (!invoice) return null;
	const c = await context(invoice.quoteId);
	const method = {
		card: `Card ${payment.reference ?? ""}`.trim(),
		bank_transfer: `Bank transfer${payment.reference ? ` (${payment.reference})` : ""}`,
		cash: "Cash",
	}[payment.method];
	const doc = (
		<Document title={payment.receiptNumber} author={c.business.name}>
			<Page size="A4" style={s.page}>
				<Header
					business={c.business}
					title="OFFICIAL RECEIPT"
					number={payment.receiptNumber}
				/>
				<Parties
					customer={c.conversation.customerName}
					right={[
						["Date", day(payment.paidAt)],
						["Invoice", invoice.number],
						["Quotation", c.quote.number],
					]}
				/>
				<Head cells={["Received for", "Amount"]} />
				<Row
					cells={[
						`${invoice.number} · ${invoice.label}`,
						formatMYR(payment.amountSen),
					]}
				/>
				<View style={s.totals}>
					<View
						style={[s.totalRow, s.bold, { borderTopWidth: 1, paddingTop: 4 }]}
					>
						<Text>Amount received</Text>
						<Text>{formatMYR(payment.amountSen)}</Text>
					</View>
				</View>
				<View style={{ marginTop: 24 }}>
					<Text style={s.muted}>Payment method: {method}</Text>
					<Text style={s.muted}>
						Balance on {c.quote.number} after this payment:{" "}
						{formatMYR(c.balanceSen)}
					</Text>
				</View>
				<Footer />
			</Page>
		</Document>
	);
	return {
		buffer: await renderToBuffer(doc),
		name: `${payment.receiptNumber}.pdf`,
	};
}

export async function renderStatementPdf(jobId: string) {
	const job = await getDb().query.jobs.findFirst({
		where: eq(schema.jobs.id, jobId),
	});
	if (!job) return null;
	const c = await context(job.quoteId);
	const lines = [
		...c.invoices.map((i) => ({
			at: i.issuedAt,
			text: `Invoice ${i.number} · ${i.label}`,
			debit: i.amountSen,
			credit: 0,
		})),
		...c.payments.map((p) => ({
			at: p.paidAt,
			text: `Payment, receipt ${p.receiptNumber}`,
			debit: 0,
			credit: p.amountSen,
		})),
	].sort((a, b) => a.at.getTime() - b.at.getTime());
	let balance = 0;
	const doc = (
		<Document title={`${job.number} statement`} author={c.business.name}>
			<Page size="A4" style={s.page}>
				<Header
					business={c.business}
					title="STATEMENT OF ACCOUNT"
					number={job.number}
				/>
				<Parties
					customer={c.conversation.customerName}
					right={[
						["Date", day(new Date())],
						["Quotation", `${c.quote.number} (${formatMYR(c.quote.totalSen)})`],
					]}
				/>
				<Head cells={["Date · Description", "Charged", "Paid", "Balance"]} />
				{lines.map((l, i) => {
					balance += l.debit - l.credit;
					return (
						<Row
							// biome-ignore lint/suspicious/noArrayIndexKey: ordered ledger
							key={i}
							cells={[
								`${day(l.at)} · ${l.text}`,
								l.debit ? formatMYR(l.debit) : "",
								l.credit ? formatMYR(l.credit) : "",
								formatMYR(balance),
							]}
						/>
					);
				})}
				<View style={s.totals}>
					<View style={s.totalRow}>
						<Text>Quotation total</Text>
						<Text>{formatMYR(c.quote.totalSen)}</Text>
					</View>
					<View style={s.totalRow}>
						<Text>Paid to date</Text>
						<Text>{formatMYR(c.paidSen)}</Text>
					</View>
					<View
						style={[s.totalRow, s.bold, { borderTopWidth: 1, paddingTop: 4 }]}
					>
						<Text>Balance remaining</Text>
						<Text>{formatMYR(c.balanceSen)}</Text>
					</View>
				</View>
				{c.plan.some(
					(p) => !c.invoices.some((i) => i.instalment === p.index),
				) ? (
					<View style={{ marginTop: 24 }}>
						<Text style={s.bold}>Still to be invoiced</Text>
						{c.plan
							.filter((p) => !c.invoices.some((i) => i.instalment === p.index))
							.map((p) => (
								<Text key={p.index} style={[s.muted, { marginTop: 2 }]}>
									• {p.label} ({p.percent}%, {triggerLabel(p)}):{" "}
									{formatMYR(p.amountSen)}
								</Text>
							))}
					</View>
				) : null}
				{c.quote.lineItems.some(
					(l) => l.charge === "monthly" || l.charge === "yearly",
				) ? (
					<Text style={[s.muted, { marginTop: 18 }]}>
						Monthly and yearly fees on the quotation are billed separately.
					</Text>
				) : null}
				<Footer />
			</Page>
		</Document>
	);
	return {
		buffer: await renderToBuffer(doc),
		name: `${job.number}-statement.pdf`,
	};
}

export async function renderCompletionReportPdf(jobId: string) {
	const db = getDb();
	const job = await db.query.jobs.findFirst({
		where: eq(schema.jobs.id, jobId),
	});
	if (!job) return null;
	const c = await context(job.quoteId);
	const [tasks, pic] = await Promise.all([
		db.query.jobTasks.findMany({
			where: eq(schema.jobTasks.jobId, job.id),
			orderBy: (t, { asc }) => [asc(t.position)],
		}),
		job.picId
			? db.query.staff.findFirst({ where: eq(schema.staff.id, job.picId) })
			: undefined,
	]);
	const finished = (ts: typeof tasks) =>
		ts.reduce<Date | null>(
			(at, t) => (t.doneAt && (!at || t.doneAt > at) ? t.doneAt : at),
			null,
		);
	const phases = c.quote.terms?.phases ?? [];
	const stages = phases.length
		? phases.map((p) => ({
				name: p.name,
				at:
					finished(tasks.filter((t) => t.phase === p.name)) ?? job.completedAt,
			}))
		: [{ name: `All work (${tasks.length} tasks)`, at: job.completedAt }];
	const doc = (
		<Document
			title={`${job.number} completion report`}
			author={c.business.name}
		>
			<Page size="A4" style={s.page}>
				<Header
					business={c.business}
					title="COMPLETION REPORT"
					number={job.number}
				/>
				<Parties
					customer={c.conversation.customerName}
					right={[
						[
							"Completed",
							job.completedAt ? day(job.completedAt) : day(new Date()),
						],
						["Started", day(job.createdAt)],
						["Quotation", c.quote.number],
						...(pic
							? ([["Person in charge", pic.name]] as [string, string][])
							: []),
					]}
				/>
				<View style={{ marginTop: 24 }}>
					<Text style={s.bold}>{job.title}</Text>
				</View>
				<View style={{ marginTop: 18 }}>
					<Text style={s.bold}>Delivered</Text>
					{c.quote.lineItems
						.filter((l) => !l.charge || l.charge === "one_time")
						.map((l, i) => (
							// biome-ignore lint/suspicious/noArrayIndexKey: lines have no id
							<Text key={i} style={{ marginTop: 3 }}>
								• {l.description}
								{l.quantity > 1 && !["hour", "day"].includes(l.unit)
									? ` × ${l.quantity} ${l.unit}`
									: ""}
							</Text>
						))}
				</View>
				{/* Customer-facing: stages and dates, not the team's internal task list. */}
				<Head cells={["Stage", "Completed on"]} />
				{stages.map((st) => (
					<Row key={st.name} cells={[st.name, st.at ? day(st.at) : ""]} />
				))}
				<View style={{ marginTop: 24 }}>
					<Text style={s.muted}>
						If anything isn't as expected, just reply in WhatsApp and our team
						will look into it.
					</Text>
				</View>
				<Footer />
			</Page>
		</Document>
	);
	return {
		buffer: await renderToBuffer(doc),
		name: `${job.number}-completion-report.pdf`,
	};
}
